FLAG_SET_CHOICES = ("reduced", "all")


def get_optimization_keys(flag_set):
    """Return a mutable copy of the requested shared flag set."""
    if flag_set == "reduced":
        return list(BINARY_OPTIMIZATION_KEYS_REDUCED)
    if flag_set == "all":
        return list(BINARY_OPTIMIZATION_KEYS_ALL)
    raise ValueError(
        f"Unknown flag set {flag_set!r}; expected one of {FLAG_SET_CHOICES}"
    )
